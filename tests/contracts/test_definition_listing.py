"""`review show UNIT --definitions` (#625): the definitions a unit's Lean uses, each once, with
its docstring, signature and body or fields, as text a reviewer reads line by line; and every
project constant those definitions use, transitively, is listed, so a blind reviewer never has to
open the sources to learn what a name means.

The site is the synthetic build of `test_compare.write_site`, with two more declarations that
only a definition the statement uses reaches: a definition and a structure. Nothing here builds
Lean."""

import hashlib
import json

from prooflens import cli
from prooflens import compare as cmp
from prooflens import review_cli as rc
from test_compare import seg, write_site

UNIT = "link:thm:t0"
WHO = "human:Listing-Reviewer"
READING = "Every statement bounds the jet uniformly in n, for every natural number n."


def key(name):
    return hashlib.sha256(name.encode()).hexdigest()[:24]


def add(data, rec):
    (data / "decls" / f"{key(rec['name'])}.json").write_text(json.dumps(rec))


def site_with_deep_uses(tmp_path):
    data = write_site(tmp_path)
    # Syn.Jet._f (in the statement's closure) uses Syn.Deep, which uses the structure Syn.Pair;
    # neither is in any statement's closure.
    p = data / "decls" / f"{key('Syn.Jet._f')}.json"
    f = json.loads(p.read_text())
    p.write_text(json.dumps({**f, "uses": ["Syn.Deep"]}))
    add(data, {"name": "Syn.Deep", "kind": "def", "module": "Syn.Defs", "fingerprint": "fp-d",
               "doc": "The second moment,\n  finite.", "signature": seg("Syn.Pair → Prop"),
               "value": seg("fun p => p.fst ≤ p.snd"), "defined_by": "body",
               "params": [{"name": "p", "binder": "explicit", "type": seg("Syn.Pair")}],
               "body": seg("p.fst ≤ p.snd"), "uses": ["Syn.Pair"]})
    add(data, {"name": "Syn.Pair", "kind": "inductive", "module": "Syn.Defs",
               "fingerprint": "fp-p", "doc": "A pair of numbers.", "signature": seg("Type"),
               "uses": [], "structure": {"class": False, "params": [], "parents": [],
                                         "fields": [
                   {"field": "fst", "kind": "data", "declared_in": "Syn.Pair",
                    "inherited": False, "type": seg("Nat")},
                   {"field": "snd", "kind": "data", "declared_in": "Syn.Pair",
                    "inherited": False, "type": seg("Nat")}]}})
    return data.parent.parent


def shown(work):
    s = rc.Session(work, rc.parse_reviewer(WHO))
    s.read(UNIT)
    s.lock(UNIT, READING)
    return s


def test_every_constant_the_definitions_use_is_listed(tmp_path):
    s = shown(site_with_deep_uses(tmp_path))
    defs = {d["name"]: d for d in s.show(UNIT, as_json=True)["lean"]["definitions"]}
    assert {"Syn.Jet", "Syn.Jet._f", "Syn.Deep", "Syn.Pair"} <= set(defs)
    assert defs["Syn.Deep"]["reached_through"] == "Syn.Jet._f"
    assert defs["Syn.Pair"]["reached_through"] == "Syn.Deep"
    assert "reached_through" not in defs["Syn.Jet"]


def test_the_listing_is_the_text_of_the_json(tmp_path):
    s = shown(site_with_deep_uses(tmp_path))
    text = s.show(UNIT, definitions=True)
    defs = s.show(UNIT, as_json=True)["lean"]["definitions"]
    # Each definition once, the generated one under its owner; no segment JSON.
    for d in defs:
        if d.get("generated_for"):
            assert f"generated by Lean: {d['name']}" in text
        else:
            assert text.count(f"\n{d['name']}  (") + text.startswith(f"{d['name']}  (") == 1
    assert '"segments"' not in text and "Syn.big_bound_" not in text
    blocks = {b.split("  (")[0]: b for b in text.split("\n\n")}
    assert blocks["Syn.Jet"].splitlines()[1:3] == [
        "  doc: A finite jet.", "  type: Nat → Nat → Prop"]
    assert blocks["Syn.Deep"].splitlines() == [
        "Syn.Deep  (def; unit def:Syn.Deep), used by Syn.Jet._f",
        "  doc: The second moment, finite.",
        "  type: Syn.Pair → Prop",
        "  defined, for (p : Syn.Pair), as: p.fst ≤ p.snd"]
    assert blocks["Syn.Pair"].splitlines()[3:] == [
        "  field fst : Nat (data)", "  field snd : Nat (data)"]


def test_the_command_prints_the_listing_after_the_lock(tmp_path, capsys, monkeypatch):
    work = site_with_deep_uses(tmp_path)
    s = rc.Session(work, rc.parse_reviewer(WHO))
    s.read(UNIT)

    class A:
        action, unit, json, definitions = "show", UNIT, False, True
    try:
        cli._review_text(A, s)
        raise AssertionError("the listing was shown before the lock")
    except rc.ReviewError as e:
        assert "lock your reading first" in str(e)
    s.lock(UNIT, READING)
    cli._review_text(A, rc.Session(work, rc.parse_reviewer(WHO)))
    out = capsys.readouterr().out
    assert out.startswith("Syn.Jet  (def; unit def:Syn.Jet)")
    assert cmp.definitions_text({"lean": {"definitions": []}}).startswith("(the Lean shown")
